export const WELCOME_NOTE_CONTENT = `# Welcome to Quick Notes

Quick Notes is a floating notepad one hotkey away. Press \`Cmd/Ctrl+Shift+N\` in any app to show or hide it. Everything is saved automatically as you write, and your notes are kept apart from the files you open in the main Sodilaud window.

## Show and hide
- Press \`Cmd/Ctrl+Shift+N\` again, press \`Cmd/Ctrl+W\`, or click the **×** at the top right to hide the panel. Clicking another app leaves it open, so a running list stays in view while you work.
- On macOS the panel opens over full-screen apps without bringing Sodilaud to the front or changing your \`Cmd+Tab\` order.
- Drag the strip at the top to move the panel, and drag an edge to resize it. It reopens where you left it, on the note you had open.
- Change the hotkey in the main window's **Sodilaud menu → Quick Notes**.

## Find your notes
- Show the note list with the sidebar button at the top left, or \`Ctrl+Cmd+S\` (\`Ctrl+Alt+S\` on Windows and Linux).
- Create a note with \`Cmd/Ctrl+N\`, or double-click the empty space below the note list. Titles come from the first line.
- Search titles and content from the sidebar, and use \`Cmd/Ctrl+F\` or \`Cmd/Ctrl+H\` to find and replace.
- Group notes with the folder button, drag a note onto a folder to move it, and pin important notes to keep them at the very top. Unpinning returns a scratchpad to its folder.
- Open a second note beside this one with \`Cmd/Ctrl+\\\`, and choose **Compare** to highlight removed text on the left and added text on the right.

## Markdown that helps as you type
- Switch between **Live**, **Source**, and **Reading** with the mode buttons, or format with the toolbar and shortcuts such as \`Cmd/Ctrl+B\`.
- Press \`Enter\` to continue lists, task lists, and quotes, and \`Tab\` or \`Shift+Tab\` to nest them or move between table cells.
- Right-click in the editor and choose **Insert** for starter tables, task lists, code blocks, and links. Paste a URL over selected text to make a link.

## Delete and recover
- Right-click a note and choose **Delete Note** to move it to trash. Click the **trash icon at the bottom right**, then **Restore**, to bring it back.
- Right-click the trash icon and choose **Empty Trash…** to remove deleted notes for good.

## Where notes are kept
- Notes stay on this device. Open a portable workspace file from this panel's menu (the button at the top right) to keep them in a file you choose.
- Agents can read and, with your permission, change these notes. Turn **Agent access** on from this panel's menu; it is off until you do.

## Settings and help
- Themes, editor zoom, line spacing, syntax highlighting, and line numbers are set in the main Sodilaud window's menu and apply to both windows. **Settings…** in this panel's menu takes you there.
- Press \`Cmd/Ctrl+/\` for keyboard shortcuts and the Markdown cheatsheet.

Happy writing.
`;
